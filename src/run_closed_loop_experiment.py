
"""
Closed-loop experiment:
Does real-time knowledge of changing Cu/Al feed composition improve
pneumatic separation compared with a fixed operating point?

This is a DIGITAL-TWIN experiment, not a claim of plant performance.

Plant:
    Existing time-resolved DynamicSeparatorSimulation.

Sensors:
    Synthetic feed camera + synthetic top-product camera with classification
    and size measurement error.

Controller:
    Physics-informed / ML-assisted controller that selects high-pulse airflow
    and duty cycle from a bounded action grid.

ML surrogate:
    HistGradientBoostingClassifier trained on trajectories generated by the
    existing dynamic separator. It predicts light/heavy/active outcome.

Experiment:
    The SAME sequence of changing true feed windows is run twice:
        A) fixed control
        B) camera-informed adaptive control

The comparison answers the research question:
    Does having real-time composition information improve the objective under
    the assumptions of this model?
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import accuracy_score

from config import (
    D_STRAIGHT,
    PNEUMATIC_FRACTION_ORDER,
    RANDOM_SEED,
    ZHU_PRIMARY_METAL_FLOW_M3_H,
)
from feed_model import generate_feed
from dynamic_separator import (
    DynamicSettings,
    DynamicSeparatorSimulation,
)
from camera_model import SyntheticCamera
from controller import AdaptiveController, flow_to_velocity


OUTPUT_DIR = Path("outputs_closed_loop")


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument(
        "--fraction",
        choices=["all", *PNEUMATIC_FRACTION_ORDER],
        default="all",
    )
    p.add_argument("--windows", type=int, default=12)
    p.add_argument("--particles-per-window", type=int, default=240)
    p.add_argument("--camera-sample", type=int, default=160)
    p.add_argument("--frequency", type=float, default=4.0)
    p.add_argument("--low-flow-fraction", type=float, default=0.35)
    p.add_argument("--duration", type=float, default=8.0)
    p.add_argument("--dt", type=float, default=0.006)
    p.add_argument(
        "--quick",
        action="store_true",
        help="Faster surrogate calibration for testing.",
    )
    p.add_argument(
        "--save-plots",
        action="store_true",
        help="Save time-series figures into outputs_closed_loop/.",
    )
    return p.parse_args()


def metal_pool_for_fraction(feed, fraction):
    return (
        feed[
            feed["pneumatic_fraction"].eq(fraction)
            & feed["material"].isin(["aluminum", "copper"])
        ]
        .copy()
        .reset_index(drop=True)
    )


def run_plant(
    feed,
    flow_m3_h,
    duty,
    frequency,
    low_flow_fraction,
    duration,
    dt,
    seed,
):
    settings = DynamicSettings(
        high_velocity_m_s=flow_to_velocity(flow_m3_h),
        low_flow_fraction=low_flow_fraction,
        pulse_frequency_hz=frequency,
        duty_cycle=duty,
        duration_s=duration,
        dt_s=dt,
    )
    sim = DynamicSeparatorSimulation(
        feed,
        settings=settings,
        n_particles=len(feed),
        seed=seed,
    )
    sim.run()
    return sim.results()


def build_suspension_lookup(pool, n_bins=18):
    lookup = {}

    for material in ["aluminum", "copper"]:
        d = pool[pool["material"].eq(material)].copy()
        if d.empty:
            continue

        lo = float(d["size_mm"].min())
        hi = float(d["size_mm"].max())
        edges = np.linspace(lo, hi, n_bins + 1)
        centers = (edges[:-1] + edges[1:]) / 2.0

        rows = []
        for i, center in enumerate(centers):
            if i == n_bins - 1:
                m = (
                    (d["size_mm"] >= edges[i])
                    & (d["size_mm"] <= edges[i + 1])
                )
            else:
                m = (
                    (d["size_mm"] >= edges[i])
                    & (d["size_mm"] < edges[i + 1])
                )

            if m.any():
                mean_us = float(
                    d.loc[m, "suspension_velocity_m_s"].mean()
                )
            else:
                mean_us = float(
                    d["suspension_velocity_m_s"].mean()
                )

            rows.append(
                {
                    "size_mm": center,
                    "mean_us": mean_us,
                }
            )

        lookup[material] = pd.DataFrame(rows)

    return lookup


def calibrate_surrogate(
    pool,
    fraction,
    args,
    rng,
):
    nominal = ZHU_PRIMARY_METAL_FLOW_M3_H[fraction]

    if args.quick:
        flows = np.array(
            [
                max(45.0, nominal - 20),
                nominal - 10,
                nominal,
                nominal + 10,
                nominal + 20,
            ]
        )
        duties = [0.40, 0.55, 0.65]
        n_each = 110
    else:
        flows = np.arange(
            max(45.0, nominal - 20),
            nominal + 20.1,
            5.0,
        )
        duties = [0.35, 0.45, 0.55, 0.65]
        n_each = 160

    records = []

    for flow in flows:
        for duty in duties:
            chosen = pool.sample(
                n=min(n_each, len(pool)),
                replace=False,
                random_state=int(rng.integers(0, 2**31 - 1)),
            ).reset_index(drop=True)

            result = run_plant(
                chosen,
                flow_m3_h=float(flow),
                duty=float(duty),
                frequency=args.frequency,
                low_flow_fraction=args.low_flow_fraction,
                duration=args.duration,
                dt=args.dt,
                seed=int(rng.integers(0, 2**31 - 1)),
            )

            block = pd.DataFrame(
                {
                    "u_s": result["suspension_velocity_m_s"].astype(float),
                    "size_mm": result["size_mm"].astype(float),
                    "flow_velocity": flow_to_velocity(flow),
                    "duty": float(duty),
                    "low_flow_fraction": args.low_flow_fraction,
                    "outcome": result["dynamic_stream"].astype(str),
                }
            )
            records.append(block)

    training = pd.concat(records, ignore_index=True)

    features = [
        "u_s",
        "size_mm",
        "flow_velocity",
        "duty",
        "low_flow_fraction",
    ]

    # Hold out every fifth row deterministically.
    test_mask = np.arange(len(training)) % 5 == 0
    train_df = training.loc[~test_mask]
    test_df = training.loc[test_mask]

    model = HistGradientBoostingClassifier(
        max_depth=5,
        learning_rate=0.08,
        max_iter=180,
        random_state=RANDOM_SEED,
    )
    model.fit(
        train_df[features],
        train_df["outcome"],
    )

    pred = model.predict(test_df[features])
    acc = accuracy_score(test_df["outcome"], pred)

    return model, training, float(acc)


def make_changing_windows(
    pool,
    n_windows,
    particles_per_window,
    rng,
):
    """
    Create a deterministic composition-disturbance pattern.

    The physical particles are sampled from the original calibrated pool;
    only the Al/Cu mixture presented to the separator changes.

    The sequence deliberately includes Al-rich, nominal, and Cu-rich periods.
    """
    # Target Al fraction follows a smooth disturbance with a second harmonic.
    phase = np.arange(n_windows, dtype=float)
    target_al = (
        0.60
        + 0.22 * np.sin(2 * np.pi * phase / max(n_windows, 2))
        + 0.08 * np.sin(4 * np.pi * phase / max(n_windows, 2) + 0.8)
    )
    target_al = np.clip(target_al, 0.28, 0.86)

    al_pool = pool[pool["material"].eq("aluminum")]
    cu_pool = pool[pool["material"].eq("copper")]

    windows = []
    for i, p_al in enumerate(target_al):
        n_al = int(round(particles_per_window * p_al))
        n_cu = particles_per_window - n_al

        al = al_pool.sample(
            n=n_al,
            replace=n_al > len(al_pool),
            random_state=int(rng.integers(0, 2**31 - 1)),
        )
        cu = cu_pool.sample(
            n=n_cu,
            replace=n_cu > len(cu_pool),
            random_state=int(rng.integers(0, 2**31 - 1)),
        )

        d = (
            pd.concat([al, cu], ignore_index=True)
            .sample(
                frac=1.0,
                random_state=int(rng.integers(0, 2**31 - 1)),
            )
            .reset_index(drop=True)
        )
        windows.append(d)

    return windows


def stream_metrics(result):
    light = result[result["dynamic_stream"].eq("light")]
    heavy = result[result["dynamic_stream"].eq("heavy")]
    active = result[result["dynamic_stream"].eq("active")]

    n_al = int(result["material"].eq("aluminum").sum())
    n_cu = int(result["material"].eq("copper").sum())

    al_light = int(light["material"].eq("aluminum").sum())
    cu_light = int(light["material"].eq("copper").sum())
    al_heavy = int(heavy["material"].eq("aluminum").sum())
    cu_heavy = int(heavy["material"].eq("copper").sum())

    al_recovery = al_light / n_al if n_al else 0.0
    cu_recovery = cu_heavy / n_cu if n_cu else 0.0

    al_purity = al_light / len(light) if len(light) else 0.0
    cu_purity = cu_heavy / len(heavy) if len(heavy) else 0.0
    unresolved = len(active) / len(result) if len(result) else 0.0

    score = (
        0.30 * al_recovery
        + 0.30 * cu_recovery
        + 0.18 * al_purity
        + 0.18 * cu_purity
        - 0.04 * unresolved
    )

    return {
        "al_recovery": al_recovery,
        "cu_recovery": cu_recovery,
        "al_purity": al_purity,
        "cu_purity": cu_purity,
        "unresolved_fraction": unresolved,
        "objective": score,
        "top_cu_true_fraction": (
            cu_light / len(light) if len(light) else 0.0
        ),
        "heavy_al_true_fraction": (
            al_heavy / len(heavy) if len(heavy) else 0.0
        ),
    }


def camera_top_summary(camera, result, max_particles=120):
    top = result[result["dynamic_stream"].eq("light")]
    obs = camera.observe_particles(
        top,
        max_particles=max_particles,
    )
    return camera.summarize(obs)


def run_strategy(
    strategy,
    windows,
    fraction,
    surrogate,
    lookup,
    args,
    seed,
):
    rng = np.random.default_rng(seed)

    feed_camera = SyntheticCamera(
        relative_size_sd=0.04,
        seed=seed + 100,
    )
    top_camera = SyntheticCamera(
        relative_size_sd=0.04,
        seed=seed + 200,
    )

    nominal = ZHU_PRIMARY_METAL_FLOW_M3_H[fraction]

    controller = AdaptiveController(
        fraction=fraction,
        surrogate=surrogate,
        suspension_lookup=lookup,
        nominal_flow_m3_h=nominal,
        frequency_hz=args.frequency,
        low_flow_fraction=args.low_flow_fraction,
    )

    rows = []

    for i, true_feed in enumerate(windows):
        feed_obs = feed_camera.observe_particles(
            true_feed,
            max_particles=args.camera_sample,
        )
        feed_summary = feed_camera.summarize(feed_obs)

        if strategy == "adaptive":
            action = controller.choose_action(feed_obs)
            flow = action["flow_m3_h"]
            duty = action["duty"]
        elif strategy == "fixed":
            action = {
                "score": np.nan,
                "feedback_action": "fixed",
            }
            flow = nominal
            duty = 0.50
        else:
            raise ValueError(strategy)

        result = run_plant(
            true_feed,
            flow_m3_h=flow,
            duty=duty,
            frequency=args.frequency,
            low_flow_fraction=args.low_flow_fraction,
            duration=args.duration,
            dt=args.dt,
            seed=seed + 1000 + i,
        )

        metrics = stream_metrics(result)
        top_summary = camera_top_summary(
            top_camera,
            result,
        )

        if strategy == "adaptive":
            controller.update_outlet_feedback(top_summary)

        true_al = float(
            true_feed["material"].eq("aluminum").mean()
        )

        rows.append(
            {
                "window": i + 1,
                "strategy": strategy,
                "fraction_mm": fraction,
                "true_al_fraction": true_al,
                "camera_al_fraction": feed_summary["aluminum_fraction"],
                "camera_cu_fraction": feed_summary["copper_fraction"],
                "flow_m3_h": flow,
                "duty": duty,
                "feedback_action": action.get(
                    "feedback_action",
                    "",
                ),
                "top_camera_cu_fraction": top_summary["copper_fraction"],
                **metrics,
            }
        )

    return pd.DataFrame(rows)


def summarize_comparison(fixed, adaptive):
    out = {
        "fixed_mean_objective": fixed["objective"].mean(),
        "adaptive_mean_objective": adaptive["objective"].mean(),
        "objective_improvement_percent": (
            100.0
            * (
                adaptive["objective"].mean()
                - fixed["objective"].mean()
            )
            / max(abs(fixed["objective"].mean()), 1e-9)
        ),
        "fixed_mean_al_recovery": fixed["al_recovery"].mean(),
        "adaptive_mean_al_recovery": adaptive["al_recovery"].mean(),
        "fixed_mean_cu_recovery": fixed["cu_recovery"].mean(),
        "adaptive_mean_cu_recovery": adaptive["cu_recovery"].mean(),
        "fixed_mean_al_purity": fixed["al_purity"].mean(),
        "adaptive_mean_al_purity": adaptive["al_purity"].mean(),
        "fixed_mean_cu_purity": fixed["cu_purity"].mean(),
        "adaptive_mean_cu_purity": adaptive["cu_purity"].mean(),
        "fixed_mean_unresolved": fixed["unresolved_fraction"].mean(),
        "adaptive_mean_unresolved": adaptive["unresolved_fraction"].mean(),
    }
    return out


def save_plots(combined, fraction):
    OUTPUT_DIR.mkdir(exist_ok=True)

    fixed = combined[combined["strategy"].eq("fixed")]
    adaptive = combined[combined["strategy"].eq("adaptive")]

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(
        fixed["window"],
        fixed["true_al_fraction"],
        marker="o",
        label="true Al fraction in changing feed",
    )
    ax.plot(
        adaptive["window"],
        adaptive["camera_al_fraction"],
        marker="x",
        label="camera-estimated Al fraction",
    )
    ax.set_xlabel("Control window")
    ax.set_ylabel("Fraction")
    ax.set_title(
        f"{fraction} mm — changing feed composition and camera estimate"
    )
    ax.legend()
    fig.tight_layout()
    fig.savefig(
        OUTPUT_DIR / f"{fraction}_feed_camera.png",
        dpi=180,
    )
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(
        adaptive["window"],
        adaptive["flow_m3_h"],
        marker="o",
        label="adaptive high-pulse flow",
    )
    ax.axhline(
        ZHU_PRIMARY_METAL_FLOW_M3_H[fraction],
        linestyle="--",
        label="fixed Zhu-reference flow",
    )
    ax.set_xlabel("Control window")
    ax.set_ylabel("High-pulse airflow (m3/h)")
    ax.set_title(
        f"{fraction} mm — controller response to changing feed"
    )
    ax.legend()
    fig.tight_layout()
    fig.savefig(
        OUTPUT_DIR / f"{fraction}_control_action.png",
        dpi=180,
    )
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(
        fixed["window"],
        fixed["objective"],
        marker="o",
        label="fixed control",
    )
    ax.plot(
        adaptive["window"],
        adaptive["objective"],
        marker="x",
        label="camera-informed adaptive control",
    )
    ax.set_xlabel("Control window")
    ax.set_ylabel("Balanced separation objective")
    ax.set_title(
        f"{fraction} mm — fixed vs adaptive separation"
    )
    ax.legend()
    fig.tight_layout()
    fig.savefig(
        OUTPUT_DIR / f"{fraction}_objective_comparison.png",
        dpi=180,
    )
    plt.close(fig)


def main():
    args = parse_args()

    OUTPUT_DIR.mkdir(exist_ok=True)

    rng = np.random.default_rng(RANDOM_SEED)
    full_feed = generate_feed()

    fractions = (
        PNEUMATIC_FRACTION_ORDER
        if args.fraction == "all"
        else [args.fraction]
    )

    all_results = []
    all_summaries = []

    for frac_index, fraction in enumerate(fractions):
        print()
        print("#" * 84)
        print(
            f"CLOSED-LOOP STUDY — {fraction} mm"
        )
        print("#" * 84)

        pool = metal_pool_for_fraction(
            full_feed,
            fraction,
        )

        lookup = build_suspension_lookup(pool)

        print("Calibrating ML surrogate from the dynamic separator...")
        surrogate, training, validation_accuracy = calibrate_surrogate(
            pool,
            fraction,
            args,
            rng,
        )

        print(
            f"Surrogate held-out outcome accuracy: "
            f"{100*validation_accuracy:.1f}%"
        )

        windows = make_changing_windows(
            pool,
            args.windows,
            args.particles_per_window,
            rng,
        )

        fixed = run_strategy(
            "fixed",
            windows,
            fraction,
            surrogate,
            lookup,
            args,
            seed=RANDOM_SEED + 10000 * frac_index,
        )

        adaptive = run_strategy(
            "adaptive",
            windows,
            fraction,
            surrogate,
            lookup,
            args,
            seed=RANDOM_SEED + 10000 * frac_index,
        )

        combined = pd.concat(
            [fixed, adaptive],
            ignore_index=True,
        )
        all_results.append(combined)

        summary = summarize_comparison(
            fixed,
            adaptive,
        )
        summary["fraction_mm"] = fraction
        summary["surrogate_validation_accuracy"] = (
            validation_accuracy
        )
        all_summaries.append(summary)

        print()
        print("RESULT:")
        print(
            f"  Fixed mean objective:    "
            f"{summary['fixed_mean_objective']:.3f}"
        )
        print(
            f"  Adaptive mean objective: "
            f"{summary['adaptive_mean_objective']:.3f}"
        )
        print(
            f"  Relative improvement:    "
            f"{summary['objective_improvement_percent']:+.1f}%"
        )

        combined.to_csv(
            OUTPUT_DIR / f"{fraction}_closed_loop_windows.csv",
            index=False,
        )
        training.to_csv(
            OUTPUT_DIR / f"{fraction}_surrogate_training.csv",
            index=False,
        )

        if args.save_plots:
            save_plots(combined, fraction)

    result_df = pd.concat(
        all_results,
        ignore_index=True,
    )
    summary_df = pd.DataFrame(all_summaries)

    result_df.to_csv(
        OUTPUT_DIR / "all_closed_loop_windows.csv",
        index=False,
    )
    summary_df.to_csv(
        OUTPUT_DIR / "closed_loop_summary.csv",
        index=False,
    )

    print()
    print("=" * 84)
    print("CROSS-FRACTION SUMMARY")
    print("=" * 84)
    cols = [
        "fraction_mm",
        "fixed_mean_objective",
        "adaptive_mean_objective",
        "objective_improvement_percent",
        "surrogate_validation_accuracy",
    ]
    print(
        summary_df[cols].to_string(
            index=False,
            float_format=lambda x: f"{x:.3f}",
        )
    )

    print()
    print(
        "Interpretation: a positive objective improvement means the "
        "camera-informed controller outperformed the fixed operating point "
        "for the exact same changing-feed windows in this digital-twin test."
    )
    print(
        "It does NOT prove the same improvement will occur experimentally; "
        "camera error, valve dynamics, separator geometry, and coating-state "
        "assumptions must later be calibrated with hardware data."
    )


if __name__ == "__main__":
    main()
